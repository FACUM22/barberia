CREATE TABLE IF NOT EXISTS users(id SERIAL PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE, hash VARCHAR(255) NOT NULL, admin SMALLINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS docs(path VARCHAR(190) PRIMARY KEY, col VARCHAR(190) NOT NULL, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS docs_col ON docs(col);
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE docs ENABLE ROW LEVEL SECURITY;
